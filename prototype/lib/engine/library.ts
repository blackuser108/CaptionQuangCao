export function emojiKitFor(category: string, tone: string) {
  const kit = library.emojiKit;
  return {
    theme: kit.theme[category] ?? kit.theme.generic,
    reactions: kit.reactions[tone] ?? kit.reactions.youthful,
    pointers: tone === 'formal' ? ['👉', '💬'] : kit.pointers,
    sparks: kit.sparks,
    byFact: kit.byFact,
  };
}

